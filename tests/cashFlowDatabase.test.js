import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readdir, readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'

const ana = '11111111-1111-4111-8111-111111111111'
const bruno = '22222222-2222-4222-8222-222222222222'

test('cash flow lists received payments by day and costs generated by created orders', async (t) => {
  const db = new PGlite()
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; set time zone 'UTC';
      create table public.sellers(id uuid primary key,name text,active boolean default true);
      create table public.orders(id text primary key,seller_id uuid,data timestamptz,nome_cliente text,status_pagamento text,
        status_rastreio text,data_pagamento date,cancelado boolean default false,product_units integer);
      create schema pgmq; create table pgmq.a_orders_ingest(msg_id bigint,enqueued_at timestamptz,message jsonb);
      insert into public.sellers values ('${ana}','Ana'),('${bruno}','Bruno');
      insert into public.orders values
        ('p1','${ana}','2026-11-20 12:00+00','Cliente 1','Pago','Entregue','2026-11-21',false,2),
        ('p2','${ana}','2026-11-21 12:00+00','Cliente 2','Pago Parcial','Em transito',null,false,1),
        ('p3','${bruno}','2026-11-20 12:00+00','Cliente 3','Chargeback','Entregue','2026-11-21',false,1),
        ('p4','${bruno}','2026-11-25 12:00+00','Cliente 4','Pago','Entregue','2026-11-30',false,1),
        ('c1','${ana}','2026-11-21 12:00+00','Cliente 5','After Pay','Cancelado',null,true,5),
        ('d1','${bruno}','2026-11-21 12:00+00','Cliente 6','After Pay','Devolvido',null,false,3);`)
    const files = await readdir(new URL('../supabase/migrations/', import.meta.url))
    for (const suffix of ['_order_financial_snapshots.sql', '_reconcile_confirmed_order_payments.sql', '_cash_flow_payments_and_costs.sql']) {
      const name = files.find(file => file.endsWith(suffix))
      assert.ok(name, `${suffix} migration exists`)
      await db.exec(await readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), 'utf8'))
    }
    const write = (id, payload, msg, at) => db.query('select public.record_order_financial_snapshot($1,$2,$3,$4)', [id, payload, msg, at])
    await write('p1', { skaletracking: { plataforma: 'PagarMe' }, transaction: { payment_status: 'Pago', paid_amount: 44700 } }, 1, '2026-11-21T15:00:00Z')
    await write('p2', { transaction: { payment_status: 'Pago Parcial', paid_amount: 20000 } }, 2, '2026-11-22T02:00:00Z')
    await write('p3', { transaction: { payment_status: 'Pago', paid_amount: 10000 } }, 3, '2026-11-21T15:00:00Z')
    await write('p3', { transaction: { payment_status: 'Chargeback' } }, 4, '2026-11-22T15:00:00Z')
    await write('p4', { transaction: { payment_status: 'Pago', paid_amount: 10000 } }, 5, '2026-11-30T15:00:00Z')
    const cashFlow = async (start, end, role = 'authenticated') => {
      await db.exec(`set role ${role}`)
      try { return (await db.query('select public.get_cash_flow($1,$2) as result', [start, end])).rows[0].result }
      finally { await db.exec('reset role') }
    }

    await t.test('payments use the payment date, or the receipt time in Brasília when it is missing', async () => {
      const result = await cashFlow('2026-11-20', '2026-11-22')
      assert.deepEqual(result.payments.map(p => [p.order_id, p.paid_date, Number(p.amount), p.estimated_date, p.seller_name]), [
        ['p1', '2026-11-21', 447, false, 'Ana'], ['p2', '2026-11-21', 200, true, 'Ana'],
      ])
      assert.equal(result.payments[0].platform, 'PagarMe')
      assert.equal(result.payments[0].customer_name, 'Cliente 1')
    })

    await t.test('generated freight and pots follow the DRE rules for created orders', async () => {
      const result = await cashFlow('2026-11-20', '2026-11-22')
      assert.deepEqual(result.generated_costs.map(c => [c.seller_name, c.freight_orders, c.units, Number(c.shipping_cost), Number(c.production_cost)]), [
        ['Ana', 2, 3, 60, 20.7], ['Bruno', 2, 1, 60, 6.9],
      ])
      assert.deepEqual(result.rates, { production: 6.9, shipping: 30 })
    })

    await t.test('validates the period and blocks anonymous access', async () => {
      await assert.rejects(cashFlow('2026-11-22', '2026-11-20'), /period/i)
      await assert.rejects(cashFlow('2025-01-01', '2026-11-20'), /period/i)
      await assert.rejects(cashFlow('2026-11-20', '2026-11-22', 'anon'), /permission denied/i)
    })
  } finally { await db.close() }
})
